"""systemd user timers: the collector every day, the review every week.

The units are rendered from the templates in ``systemd/``, checked with
``systemd-analyze verify`` in a temporary folder and only then written to the user unit
folder. Files are only overwritten or removed when they carry :data:`MARKER`, so units
written by hand are never touched without ``--force``.
"""

import contextlib
import os
import re
import shutil
import sys
import tempfile
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from importlib.resources import files
from pathlib import Path
from string import Template

from obsidian_agent_backend.daily_note import atomic_write
from obsidian_agent_backend.domain import SourceError
from obsidian_agent_backend.sources import Runner

MARKER = "# Generated by oab-timers (rewrite: oab-timers install, remove: oab-timers uninstall)"
DOCS = "https://github.com/Restring17/obsidian-agent-backend#scheduling"
UNITS = ("oab-collect.service", "oab-collect.timer", "oab-review.service", "oab-review.timer")
TIMERS = ("oab-collect.timer", "oab-review.timer")
DEFAULT_COLLECT_AT = "*-*-* 09:00"
DEFAULT_REVIEW_AT = "Mon *-*-* 09:30"
# OnCalendar expressions only need these characters; anything else (newlines above all)
# could inject settings into the unit file.
CALENDAR = re.compile(r"^[A-Za-z0-9 ,:*/.~+-]{1,64}$")
# Tools the units call, so their folders go into PATH (systemd starts with a minimal one).
TOOLS = ("git", "gh", "claude")
BASE_PATH = ("/usr/local/bin", "/usr/bin", "/bin")

type Which = Callable[[str], str | None]


class TimerError(Exception):
    """The units cannot be rendered, checked, installed or removed."""


@dataclass(frozen=True, slots=True)
class Schedule:
    config: Path  # absolute path to oab.toml
    collect: Path  # absolute path to the oab-collect executable
    review: Path  # absolute path to the oab-review executable
    path: tuple[str, ...]  # PATH for the services
    collect_at: str  # OnCalendar, timezone included
    review_at: str
    github: bool = True


def calendar(text: str) -> str:
    """Validate an OnCalendar expression without a timezone (the vault's is appended)."""
    if not CALENDAR.match(text):
        raise ValueError(f"invalid calendar expression: {text!r}")
    return text


def quote(arg: str, *, expands_variables: bool = False) -> str:
    """Quote a unit file value: spaces kept and ``%`` specifiers not expanded.

    systemd expands ``$VAR`` only in the arguments of an Exec line (not in the executable
    path, nor in ``Environment=``), so only there ``$`` is written as ``$$``.
    """
    if any(char in arg for char in "\n\r\0"):
        raise TimerError(f"cannot use a line break in a unit file: {arg!r}")
    escaped = arg.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if expands_variables:
        escaped = escaped.replace("$", "$$")
    return f'"{escaped}"'


def _exec_line(executable: Path, *args: str) -> str:
    quoted = [quote(arg, expands_variables=True) for arg in args]
    return " ".join([quote(str(executable)), *quoted])


def find_command(name: str, which: Which = shutil.which) -> Path:
    """The executable on PATH, else the one next to this Python (a ``uv run`` checkout)."""
    found = which(name)
    if found:
        return Path(found).absolute()
    sibling = Path(sys.executable).parent / name
    if sibling.is_file() and os.access(sibling, os.X_OK):
        return sibling
    raise TimerError(f"{name} not found: install the package first (uv tool install .)")


def search_path(executables: Sequence[Path], which: Which = shutil.which) -> tuple[str, ...]:
    """Folders of our executables and of git, gh and claude, then the system folders."""
    folders = [str(exe.parent) for exe in executables]
    folders += [str(Path(found).absolute().parent) for tool in TOOLS if (found := which(tool))]
    unique = dict.fromkeys(folder for folder in [*folders, *BASE_PATH] if ":" not in folder)
    return tuple(unique)


def render(schedule: Schedule) -> dict[str, str]:
    """The four unit files, by name."""
    config = ("--config", str(schedule.config))
    github = () if schedule.github else ("--no-github",)
    values = {
        "marker": MARKER,
        "docs": DOCS,
        "path": quote("PATH=" + ":".join(schedule.path)),
        "collect": _exec_line(schedule.collect, *config, *github),
        "review": _exec_line(schedule.review, *config),
        "collect_at": schedule.collect_at,
        "review_at": schedule.review_at,
    }
    templates = files("obsidian_agent_backend").joinpath("systemd")
    return {
        name: Template(templates.joinpath(name).read_text(encoding="utf-8")).substitute(values)
        for name in UNITS
    }


def unit_folder(environ: Mapping[str, str] = os.environ) -> Path:
    """``$XDG_CONFIG_HOME/systemd/user``, by default ``~/.config/systemd/user``."""
    base = environ.get("XDG_CONFIG_HOME", "")
    root = Path(base) if base and Path(base).is_absolute() else Path.home() / ".config"
    return root / "systemd" / "user"


def _ours(path: Path) -> bool:
    try:
        return MARKER in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def verify(units: Mapping[str, str], runner: Runner, user: bool = True) -> None:
    """``systemd-analyze verify`` on a temporary copy, before anything is installed."""
    with tempfile.TemporaryDirectory(prefix="oab-units-") as tmp:
        paths = []
        for name, text in units.items():
            path = Path(tmp) / name
            path.write_text(text, encoding="utf-8")
            paths.append(str(path))
        scope = ["--user"] if user else []
        try:
            runner(["systemd-analyze", *scope, "verify", *paths], None)
        except SourceError as exc:
            raise TimerError(f"the units do not pass systemd-analyze verify: {exc}") from None


def install(
    units: Mapping[str, str], folder: Path, runner: Runner, *, force: bool = False
) -> list[Path]:
    """Write the units and enable both timers now. Returns the written files."""
    targets = [folder / name for name in units]
    foreign = [path for path in targets if path.exists() and not _ours(path)]
    if foreign and not force:
        names = ", ".join(str(path) for path in foreign)
        raise TimerError(f"not written by oab-timers, use --force to replace: {names}")
    verify(units, runner)
    for path, text in zip(targets, units.values(), strict=True):
        atomic_write(path, text)
    try:
        runner(["systemctl", "--user", "daemon-reload"], None)
        runner(["systemctl", "--user", "enable", "--now", *TIMERS], None)
    except SourceError as exc:
        raise TimerError(f"units written to {folder}, but systemctl failed: {exc}") from None
    return targets


def uninstall(folder: Path, runner: Runner) -> tuple[list[Path], list[Path]]:
    """Disable both timers and remove our unit files. Returns (removed, kept)."""
    # Not installed or not loaded is fine: the files are still cleaned up.
    with contextlib.suppress(SourceError):
        runner(["systemctl", "--user", "disable", "--now", *TIMERS], None)
    removed, kept = [], []
    for name in UNITS:
        path = folder / name
        if not path.exists():
            continue
        if _ours(path):
            path.unlink()
            removed.append(path)
        else:
            kept.append(path)
    try:
        runner(["systemctl", "--user", "daemon-reload"], None)
    except SourceError as exc:
        raise TimerError(f"units removed, but systemctl failed: {exc}") from None
    return removed, kept
